public class RightShiftDemo{
    public static void main(String[] args) {
        int a = 17;
        int b = 23;

        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("a >> 2 = " + (a >> 2));
        System.out.println("a >> 3 = " + (a >> 3));
        System.out.println("b << 4 = " + (a << 4));
    }
}

       